    public void setProducto(Modelo.Productos producto) {

        this.producto = producto;

        // Nombre
        EtqNomProducto.setText(producto.getNombre());

        // Precio
        EtqCostoVenta.setText(String.format("$ %.2f", producto.getPrecio()));

        // Existencia
        EtqDisponibilidad.setText("Disponibles: "+ producto.getUnidades());

        // Imagen
        cargarImagen(producto.getImagen());

        // Si no hay unidades deshabilitar botón
        BtnAgregar.setEnabled(producto.getUnidades() > 0);
    }

    private void cargarImagen(String rutaImagen) {

        try {
            ImageIcon icon = new ImageIcon(rutaImagen);
            Image imagenEscalada =icon.getImage().getScaledInstance(EtqImgProducto.getWidth(),EtqImgProducto.getHeight(),Image.SCALE_SMOOTH );
            EtqImgProducto.setIcon(new ImageIcon(imagenEscalada));
            EtqImgProducto.setText("");

        } catch (Exception e) {
            EtqImgProducto.setIcon(null);
            EtqImgProducto.setText("Sin imagen");
        }
    }

